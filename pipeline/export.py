"""Stage 5 - Export seed data (CSV + JSON) and chunks.jsonl to data/processed/, plus generated
SOURCES.md and reports/quality_stats.md (numbers for the data-quality report)."""
from __future__ import annotations

import csv
import json
from collections import Counter
from datetime import date

from .paths import PROCESSED, ROOT

TABLES = ["courses", "prerequisites", "rules", "resources", "resource_courses", "skills", "course_skills",
          "resource_skills", "modules", "programme_requirements", "semester_slots"]
# fields that are legitimately empty by design are excluded from fill-rate (documented in DATA_QUALITY.md)
FILL_FIELDS = {
    "courses": ["code", "title", "department", "credits", "semesters_offered", "course_type", "mode", "syllabus",
                "prereq_text", "overlap_text", "source_url", "retrieved_on"],
    "rules": ["rule_id", "category", "text", "numeric_limit", "unit", "applies_to", "page", "source_url"],
    "resources": ["title", "provider", "licence", "format", "duration_hours_est", "instructor", "description",
                  "maps_to_courses", "source_url", "retrieved_on"],
    "prerequisites": ["course_code", "requires_code", "kind", "group_logic"],
    "skills": ["skill_id", "name", "parent_skill", "level"],
}


def _flat(v):
    if isinstance(v, (list, dict)):
        return json.dumps(v, ensure_ascii=False)
    return "" if v is None else v


def _write(name: str, rows: list[dict]) -> None:
    (PROCESSED / f"{name}.json").write_text(json.dumps(rows, indent=2, ensure_ascii=False), encoding="utf-8")
    if not rows:
        return
    fields = list(dict.fromkeys(k for r in rows for k in r))
    with open(PROCESSED / f"{name}.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in rows:
            w.writerow({k: _flat(r.get(k)) for k in fields})


def fill_rates(kb: dict) -> dict:
    out = {}
    for ent, fields in FILL_FIELDS.items():
        rows = kb[ent]
        out[ent] = {f: round(100 * sum(1 for r in rows if r.get(f) not in (None, "", [])) / len(rows), 1)
                    for f in fields} if rows else {}
    return out


def write_sources_md(manifest: dict) -> None:
    lines = ["# SOURCES", "",
             "Generated by `run_pipeline.py` from `data/raw/manifest.json` (do not edit by hand).",
             "Every record in `data/processed/` carries `source_id` / `source_url` pointing to one of these.", "",
             "| source_id | Title | URL (as fetched) | Retrieved on | Type | Licence | Raw file | sha256 (12) |",
             "|---|---|---|---|---|---|---|---|"]
    for sid, e in manifest.items():
        lines.append(f"| {sid} | {e['title']} | {e['url']} | {e.get('retrieved_on','')} | {e['source_type']} | "
                     f"{e['licence']} | `data/raw/{e['file']}` | {e.get('sha256','')[:12]} |")
    lines += ["", "## Manually curated inputs (`data/manual/`)", "",
              "| File | What | Basis |", "|---|---|---|",
              "| resources_seed.csv | which open resources to fetch + course mapping + licence | licence from provider "
              "site terms (NPTEL: CC BY-SA 4.0; MIT OCW & Missing Semester: CC BY-NC-SA 4.0); titles/lessons are NOT "
              "typed by hand, they are read from the fetched snapshot |",
              "| rules_seed.csv | start/end anchors of each rule in the official PDFs + numeric limit | rule text itself "
              "is extracted verbatim from the PDF by the pipeline; fails if an anchor is missing |",
              "| skills.csv | skill taxonomy + keywords for deterministic course/resource-skill linking | authored |",
              "| code_aliases.csv | legacy (CoS-2023) -> current (CoS-2026) course codes | title/syllabus match, basis per row |",
              "| validation_waivers.csv | accepted validator exceptions | reason per row |"]
    (ROOT / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def run(kb: dict, chunks: list[dict], report: dict) -> None:
    PROCESSED.mkdir(parents=True, exist_ok=True)
    known = set(kb["all_course_codes"])
    for e in kb["prerequisites"]:
        e["requires_in_catalogue"] = e["requires_code"] in known
    for t in TABLES:
        _write(t, kb[t])
    with open(PROCESSED / "chunks.jsonl", "w", encoding="utf-8") as f:
        for c in chunks:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")

    stats = {
        "generated_on": date.today().isoformat(),
        "counts": {t: len(kb[t]) for t in TABLES} | {"chunks": len(chunks)},
        "chunks_by_type": dict(Counter(c["chunk_type"] for c in chunks)),
        "chunk_words": {"min": min(c["n_words"] for c in chunks), "max": max(c["n_words"] for c in chunks),
                        "mean": round(sum(c["n_words"] for c in chunks) / len(chunks), 1)},
        "courses_by_type": dict(Counter(c["course_type"] for c in kb["courses"])),
        "courses_by_category": dict(Counter(c["category"] for c in kb["courses"])),
        "rules_by_category": dict(Counter(r["category"] for r in kb["rules"])),
        "resources_by_provider": dict(Counter(r["provider"] for r in kb["resources"])),
        "fill_rate_percent": fill_rates(kb),
        "validation": {k: len(report[k]) for k in ("errors", "warnings", "waived", "info")},
    }
    (PROCESSED / "validation_report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    (PROCESSED / "quality_stats.json").write_text(json.dumps(stats, indent=2, ensure_ascii=False), encoding="utf-8")
    write_sources_md(kb["manifest"])

    md = ["# Quality stats (generated)", "", "## Counts", "", "| Entity | Count |", "|---|---|"]
    md += [f"| {k} | {v} |" for k, v in stats["counts"].items()]
    md += ["", "## Fill rate per field (%)", ""]
    for ent, fr in stats["fill_rate_percent"].items():
        md += [f"**{ent}**: " + ", ".join(f"{k} {v}" for k, v in fr.items()), ""]
    md += ["## Validator findings", ""]
    for k in ("errors", "waived", "warnings", "info"):
        for f in report[k]:
            md.append(f"- **{k[:-1] if k != 'info' else 'info'}** `{f['check']}` {f['record']}: {f['detail']}"
                      + (f" - waiver: {f['waiver_reason']}" if f.get("waiver_reason") else ""))
    md += ["", "## Legacy-code resolutions", ""]
    md += [f"- {a['course']}: `{a['raw']}` -> `{a['resolved_to']}`" for a in report["legacy_alias_resolutions"]]
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "quality_stats.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"[export] {len(TABLES)} tables + chunks.jsonl ({len(chunks)}) -> {PROCESSED}; SOURCES.md, reports/quality_stats.md")
